package com.streamtranslate.backend.auth;

// Тип нашого JWT. Кладеться в claim "type" при видачі й перевіряється при використанні.
//
// Навіщо: обидва токени підписані тим самим секретом і мають той самий claim "sub",
// тож без цієї позначки вони структурно НЕРОЗРІЗНЯННІ. Наслідок був подвійний:
//
//   1. Access-токен приймався в POST /auth/refresh, тобто вкрадений короткоживучий
//      токен можна було нескінченно продовжувати, обмінюючи на новий. 15-хвилинний
//      TTL — головний запобіжник у нашій моделі — знецінювався повністю.
//   2. Refresh-токен приймався як access у звичайних запитах до API. А він живе
//      30 днів, тобто його крадіжка коштувала б значно дорожче.
//
// Тепер кожен токен придатний рівно для свого призначення.
public enum TokenType {
    ACCESS,
    REFRESH;

    // У claim пишемо малими літерами: "access" / "refresh".
    public String claimValue() {
        return name().toLowerCase();
    }
}
